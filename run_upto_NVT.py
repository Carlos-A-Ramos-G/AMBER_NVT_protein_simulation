#!/usr/bin/env python3
"""
NVT protein MD workflow manager for AMBER.

Commands
--------
  python run_upto_NVT.py setup  [--config config.yaml] [--mode MODE] [--submit]
  python run_upto_NVT.py submit [--config config.yaml] [--mode MODE]

  setup   Generate all input and job scripts.
          Pass --submit to also launch immediately after.
  submit  Submit existing scripts without regenerating files.
          Use this after manually editing generated scripts.

Modes
-----
  cluster  (default) SLURM; master job runs stages 00-03, then chains
           NVT chunk jobs via sbatch.
  local    No SLURM.  Generates run_local for a single-GPU workstation.
"""

