def _submit(cfg: dict, mode: str) -> None:
    if mode == "local":
        script = REPL_ROOT / "run_local"
        if not script.exists():
            sys.exit("run_local not found. Run 'setup --mode local' first.")
        log = REPL_ROOT / "run.log"
        proc = subprocess.Popen(
            ["bash", str(script)],
            stdout=log.open("w"),
            stderr=subprocess.STDOUT,
            start_new_session=True,
        )
        print(f"\nLaunched run_local in background (PID {proc.pid}).")
        print(f"  log  → {log}")
        print(f"  stop → kill {proc.pid}")
    else:
        script = REPL_ROOT / "run_gpu"
        if not script.exists():
            sys.exit("run_gpu not found. Run 'setup' first.")
        if not shutil.which("sbatch"):
            sys.exit("sbatch not on PATH. Submit manually: sbatch run_gpu")
        result = subprocess.run(
            ["sbatch", "run_gpu"], capture_output=True, text=True, cwd=str(REPL_ROOT),
        )
        if result.returncode == 0:
            print(f"\n{result.stdout.strip()}")
        else:
            sys.exit(f"sbatch failed: {result.stderr.strip()}")


