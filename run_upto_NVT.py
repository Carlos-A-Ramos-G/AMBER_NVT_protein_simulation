def _write_exe(path: Path, content: str) -> None:
    path.write_text(content)
    path.chmod(0o755)


def setup(cfg: dict, mode: str = "cluster", submit: bool = False) -> None:
    if mode not in ("cluster", "local"):
        sys.exit(f"Unknown mode '{mode}'. Choose: cluster, local.")

    use_hmr  = bool(cfg.get("use_hmr", True))
    dt       = 0.004 if use_hmr else 0.002
    topology = "structure_HMR.parm7" if use_hmr else "structure.parm7"
    temp     = float(cfg["temperature"])

    validate_inputs(cfg)
    run_propka(cfg)

    print(f"\nMode     : {mode}")
    print(f"HMR      : {use_hmr}  (dt={dt} ps, topology={topology})")
    print(f"Temp     : {temp} K")
    print(f"Chunks   : {cfg['total_chunks']} × {cfg['ns_per_chunk']} ns")
    print()
    print("Writing input files ...")

    # ---- leap_structure ------------------------------------------------
    src = REPL_ROOT / "00_prep" / "leap_structure_tmp"
    dst = REPL_ROOT / "00_prep" / "leap_structure"
    text = re.sub(r"loadpdb\s+\S+", f"loadpdb {cfg['pdb']}", src.read_text())
    dst.write_text(text)
    print(f"  wrote 00_prep/leap_structure")

    # ---- 01_min/min.in -------------------------------------------------
    min_cfg = cfg["min"]
    (REPL_ROOT / "01_min" / "min.in").write_text(
        _MIN_TEMPLATE.format(
            maxcyc=min_cfg["maxcyc"],
            ncyc=min_cfg["ncyc"],
            cut=min_cfg["cut"],
        )
    )
    print("  wrote 01_min/min.in")

    # ---- 02_heat/heat.in -----------------------------------------------
    heat_steps = int(round(float(cfg["heat"]["ps"]) / dt))
    ramp_end   = int(round(0.8 * heat_steps))
    (REPL_ROOT / "02_heat" / "heat.in").write_text(
        _HEAT_TEMPLATE.format(
            temp0=temp,
            nstlim=heat_steps,
            dt=dt,
            ramp_end=ramp_end,
        )
    )
    print("  wrote 02_heat/heat.in")

    # ---- 03_equil/equil_N.in  (cycles 1-5 NPT, cycle 6 NVT) -----------
    npt_steps = int(round(float(cfg["equil"]["npt_ns"]) * 1000.0 / dt))
    nvt_steps = int(round(float(cfg["equil"]["nvt_ns"]) * 1000.0 / dt))
    equil_dir = REPL_ROOT / "03_equil"
    for cycle in range(1, 6):
        wt = 15.0 - (cycle - 1) * 3.0   # 15, 12, 9, 6, 3
        (equil_dir / f"equil_{cycle}.in").write_text(
            _EQUIL_NPT_TEMPLATE.format(
                cycle=cycle, nstlim=npt_steps, dt=dt, temp=temp, wt=wt,
            )
        )
    (equil_dir / "equil_6.in").write_text(
        _EQUIL_NVT_TEMPLATE.format(nstlim=nvt_steps, dt=dt, temp=temp)
    )
    print("  wrote 03_equil/equil_{1..6}.in")

    # ---- 04_NVT/prod.in ------------------------------------------------
    prod_cfg   = cfg["prod"]
    prod_steps = int(round(float(cfg["ns_per_chunk"]) * 1000.0 / dt))
    (REPL_ROOT / "04_NVT" / "prod.in").write_text(
        _PROD_TEMPLATE.format(
            nstlim=prod_steps, dt=dt, temp=temp,
            ntpr=prod_cfg["ntpr"],
            ntwx=prod_cfg["ntwx"],
            ntwr=prod_cfg["ntwr"],
        )
    )
    print("  wrote 04_NVT/prod.in")

    # ---- master run script + NVT job scripts ---------------------------
    if mode == "cluster":
        _write_exe(REPL_ROOT / "run_gpu", _gen_run_gpu(cfg, topology))
        print("  wrote run_gpu")

        total_chunks  = int(cfg["total_chunks"])
        chunks_per_job = int(cfg["chunks_per_job"])
        n_jobs = math.ceil(total_chunks / chunks_per_job)
        for job_idx in range(1, n_jobs + 1):
            start = (job_idx - 1) * chunks_per_job + 1
            end   = min(job_idx * chunks_per_job, total_chunks)
            p = REPL_ROOT / "04_NVT" / f"nvt_job_{job_idx}.cmd"
            _write_exe(p, _gen_nvt_cluster_job(job_idx, start, end, total_chunks, cfg, topology))
        print(f"  wrote 04_NVT/nvt_job_{{1..{n_jobs}}}.cmd")
    else:
        _write_exe(REPL_ROOT / "run_local", _gen_run_local(cfg, topology))
        print("  wrote run_local")

    print("\nSetup complete.")

    if submit:
        _submit(cfg, mode)


