def main() -> None:
    parser = argparse.ArgumentParser(
        description="NVT protein MD workflow manager for AMBER.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument(
        "--config", default="config.yaml",
        help="Configuration file (default: config.yaml)",
    )

    sub = parser.add_subparsers(dest="command", required=True)

    p_setup = sub.add_parser("setup", help="Generate all input files and run scripts")
    p_setup.add_argument(
        "--mode", default="cluster", choices=["cluster", "local"],
        help="cluster (SLURM, default) or local (single GPU workstation)",
    )
    p_setup.add_argument(
        "--submit", action="store_true",
        help="Launch run_gpu (sbatch) or run_local (bash) after generating files",
    )

    p_submit = sub.add_parser(
        "submit", help="Submit existing scripts without regenerating files",
    )
    p_submit.add_argument(
        "--mode", default="cluster", choices=["cluster", "local"],
        help="Must match the mode used during setup (default: cluster)",
    )

    args = parser.parse_args()

    config_path = Path(args.config)
    if not config_path.exists():
        sys.exit(f"Config file not found: {config_path}")

    with open(config_path) as fh:
        cfg = yaml.safe_load(fh)

    if args.command == "setup":
        setup(cfg, mode=args.mode, submit=args.submit)
    elif args.command == "submit":
        _submit(cfg, mode=args.mode)


if __name__ == "__main__":
    main()
