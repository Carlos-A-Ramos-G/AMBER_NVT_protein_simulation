def _gen_run_gpu(cfg: dict, topology: str) -> str:
    slurm = cfg["slurm"]["master"]
    hmr_block = "cpptraj -i HMR.ccptraj" if cfg.get("use_hmr", True) else "# HMR disabled"
    return (
        _RUN_GPU_TEMPLATE
        .replace("__WALLTIME_MASTER__", str(slurm.get("time", "1-00:00:00")))
        .replace("__NTASKS_MASTER__", str(slurm.get("ntasks", 1)))
        .replace("__GRES_MASTER__", str(slurm.get("gres", "gpu:1")))
        .replace("__PARTITION_MASTER__", str(slurm.get("partition", "gpu")))
        .replace("__JOB_NAME__", str(cfg.get("job_name", "NVT")))
        .replace("__ACCOUNT_MASTER__", str(slurm.get("account", "")))
        .replace("__AMBER_MODULE__", str(cfg["amber"]["module"]))
        .replace("__HMR_BLOCK__", hmr_block)
        .replace("__MIN_CYCLES_CAP__", str(cfg["min"]["max_cycles_cap"]))
        .replace("__CONV_THRESH__", str(cfg["min"]["convergence_threshold"]))
        .replace("__TOPOLOGY__", topology)
    )


def _gen_run_local(cfg: dict, topology: str) -> str:
    amber_home = cfg.get("amber_home", "").strip()
    amber_setup = (
        f'source "{amber_home}/amber.sh"' if amber_home
        else "# pmemd.cuda assumed to be on PATH"
    )
    hmr_block = "cpptraj -i HMR.ccptraj" if cfg.get("use_hmr", True) else "# HMR disabled"
    return (
        _RUN_LOCAL_TEMPLATE
        .replace("__AMBER_SETUP__", amber_setup)
        .replace("__HMR_BLOCK__", hmr_block)
        .replace("__MIN_CYCLES_CAP__", str(cfg["min"]["max_cycles_cap"]))
        .replace("__CONV_THRESH__", str(cfg["min"]["convergence_threshold"]))
        .replace("__TOPOLOGY__", topology)
        .replace("__TOTAL_CHUNKS__", str(cfg["total_chunks"]))
    )


def _gen_nvt_cluster_job(job_idx: int, start_chunk: int, end_chunk: int,
                          total_chunks: int, cfg: dict, topology: str) -> str:
    slurm = cfg["slurm"]["nvt"]
    next_job = f"\nsbatch nvt_job_{job_idx + 1}.cmd" if end_chunk < total_chunks else ""
    return (
        _NVT_JOB_TEMPLATE
        .replace("__WALLTIME_NVT__", str(slurm.get("time", "5-00:00:00")))
        .replace("__NTASKS_NVT__", str(slurm.get("ntasks", 1)))
        .replace("__GRES_NVT__", str(slurm.get("gres", "gpu:1")))
        .replace("__PARTITION_NVT__", str(slurm.get("partition", "gpu")))
        .replace("__JOB_IDX__", str(job_idx))
        .replace("__ACCOUNT_NVT__", str(slurm.get("account", "")))
        .replace("__AMBER_MODULE__", str(cfg["amber"]["module"]))
        .replace("__START__", str(start_chunk))
        .replace("__END__", str(end_chunk))
        .replace("__TOTAL__", str(total_chunks))
        .replace("__TOPOLOGY__", topology)
        .replace("__NEXT_JOB__", next_job)
    )


