def _write_exe(path: Path, content: str) -> None:
    path.write_text(content)
    path.chmod(0o755)


def setup(cfg: dict, mode: str = "cluster", submit: bool = False) -> None:
    if mode not in ("cluster", "local"):
        sys.exit(f"Unknown mode '{mode}'. Choose: cluster, local.")

    use_hmr  = bool(cfg.get("use_hmr", True))
    dt       = 0.004 if use_hmr else 0.002
    topology = "structure_HMR.parm7" if use_hmr else "structure.parm7"
    temp     = float(cfg["temperature"])

    restr_cfg     = cfg.get("restraints", {})
    restr_enabled = bool(restr_cfg.get("enabled", False))
    restr_file    = restr_cfg.get("file", "").strip() if restr_enabled else ""
    restr_rel     = f"../{restr_file}" if restr_enabled else ""

    # Strings injected into each AMBER .in template
    nmropt_cntrl   = "\n  nmropt = 1," if restr_enabled else ""
    disang_full    = f"&wt type='END' /\nDISANG = {restr_rel}\n" if restr_enabled else ""
    disang_heat    = f"\nDISANG = {restr_rel}" if restr_enabled else ""
    disang_equil   = f"DISANG = {restr_rel}\n" if restr_enabled else ""

    validate_inputs(cfg)

    print(f"\nMode       : {mode}")
    print(f"HMR        : {use_hmr}  (dt={dt} ps, topology={topology})")
    print(f"Temp       : {temp} K")
    print(f"Restraints : {'enabled  (' + restr_file + ')' if restr_enabled else 'off'}")
    print(f"Chunks     : {cfg['total_chunks']} × {cfg['ns_per_chunk']} ns")
    print()
    print("Writing input files ...")

    # ---- stage directories ---------------------------------------------
    for d in ["01_min", "02_heat", "03_equil", "04_NVT"]:
        (REPL_ROOT / d).mkdir(exist_ok=True)

    # ---- leap_structure ------------------------------------------------
    (REPL_ROOT / "00_prep" / "leap_structure").write_text(_render_leap(cfg))
    print("  wrote 00_prep/leap_structure")

    # ---- HMR.ccptraj ---------------------------------------------------
    if use_hmr:
        (REPL_ROOT / "00_prep" / "HMR.ccptraj").write_text(_HMR_TEMPLATE)
        print("  wrote 00_prep/HMR.ccptraj")

    # ---- 01_min/min.in -------------------------------------------------
    min_cfg = cfg["min"]
    (REPL_ROOT / "01_min" / "min.in").write_text(
        _MIN_TEMPLATE.format(
            maxcyc=min_cfg["maxcyc"],
            ncyc=min_cfg["ncyc"],
            cut=min_cfg["cut"],
            nmropt_cntrl=nmropt_cntrl,
            disang_tail=disang_full,
        )
    )
    print("  wrote 01_min/min.in")

    # ---- 02_heat/heat.in -----------------------------------------------
    heat_steps = int(round(float(cfg["heat"]["ps"]) / dt))
    ramp_end   = int(round(0.8 * heat_steps))
    (REPL_ROOT / "02_heat" / "heat.in").write_text(
        _HEAT_TEMPLATE.format(
            temp0=temp,
            nstlim=heat_steps,
            dt=dt,
            ramp_end=ramp_end,
            disang_tail=disang_heat,
        )
    )
    print("  wrote 02_heat/heat.in")

    # ---- 03_equil/equil_N.in  (cycles 1-5 NPT, cycle 6 NVT) -----------
    npt_steps = int(round(float(cfg["equil"]["npt_ns"]) * 1000.0 / dt))
    nvt_steps = int(round(float(cfg["equil"]["nvt_ns"]) * 1000.0 / dt))
    equil_dir = REPL_ROOT / "03_equil"
    for cycle in range(1, 6):
        wt = 15.0 - (cycle - 1) * 3.0   # 15, 12, 9, 6, 3
        (equil_dir / f"equil_{cycle}.in").write_text(
            _EQUIL_NPT_TEMPLATE.format(
                cycle=cycle, nstlim=npt_steps, dt=dt, temp=temp, wt=wt,
                nmropt_cntrl=nmropt_cntrl, disang_tail=disang_equil,
            )
        )
    (equil_dir / "equil_6.in").write_text(
        _EQUIL_NVT_TEMPLATE.format(
            nstlim=nvt_steps, dt=dt, temp=temp,
            nmropt_cntrl=nmropt_cntrl, disang_tail=disang_equil,
        )
    )
    print("  wrote 03_equil/equil_{1..6}.in")

    # ---- 04_NVT/prod.in ------------------------------------------------
    prod_cfg   = cfg["prod"]
    prod_steps = int(round(float(cfg["ns_per_chunk"]) * 1000.0 / dt))
    (REPL_ROOT / "04_NVT" / "prod.in").write_text(
        _PROD_TEMPLATE.format(
            nstlim=prod_steps, dt=dt, temp=temp,
            ntpr=prod_cfg["ntpr"],
            ntwx=prod_cfg["ntwx"],
            ntwr=prod_cfg["ntwr"],
            nmropt_cntrl=nmropt_cntrl,
            disang_tail=disang_full,
        )
    )
    print("  wrote 04_NVT/prod.in")

    # ---- master run script + NVT job scripts ---------------------------
    total_chunks   = int(cfg["total_chunks"])
    chunks_per_job = int(cfg["chunks_per_job"])
    n_jobs = math.ceil(total_chunks / chunks_per_job)

    out_name = "run_gpu" if mode == "cluster" else "run_local"
    _write_exe(REPL_ROOT / out_name, _gen_run_script(cfg, topology, mode))
    print(f"  wrote {out_name}")

    for job_idx in range(1, n_jobs + 1):
        start = (job_idx - 1) * chunks_per_job + 1
        end   = min(job_idx * chunks_per_job, total_chunks)
        fname = (f"run_NVT_{job_idx}.cmd" if mode == "cluster"
                 else f"run_NVT_{job_idx}_local.sh")
        _write_exe(REPL_ROOT / "04_NVT" / fname,
                   _gen_nvt_job(job_idx, start, end, total_chunks, cfg, topology, mode))
    ext = "cmd" if mode == "cluster" else "local.sh"
    if n_jobs == 1:
        print(f"  wrote 04_NVT/run_NVT_1.{ext}")
    else:
        print(f"  wrote 04_NVT/run_NVT_{{1..{n_jobs}}}.{ext}")

    print("\nSetup complete.")

    if submit:
        _submit(cfg, mode)


