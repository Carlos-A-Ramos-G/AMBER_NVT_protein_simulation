def _submit(cfg: dict, mode: str) -> None:
    if mode == "local":
        script = REPL_ROOT / "run_local"
        if not script.exists():
            sys.exit("run_local not found. Run 'setup --mode local' first.")
        log = REPL_ROOT / "run.log"
        proc = subprocess.Popen(
            ["bash", str(script)],
            stdout=log.open("w"),
            stderr=subprocess.STDOUT,
            start_new_session=True,
        )
        print(f"\nLaunched run_local in background (PID {proc.pid}).")
        print(f"  log  → {log}")
        print(f"  stop → kill {proc.pid}")
    else:
        script = REPL_ROOT / "run_gpu"
        if not script.exists():
            sys.exit("run_gpu not found. Run 'setup' first.")
        if not shutil.which("sbatch"):
            sys.exit("sbatch not on PATH. Submit manually: sbatch run_gpu")
        result = subprocess.run(
            ["sbatch", "run_gpu"], capture_output=True, text=True, cwd=str(REPL_ROOT),
        )
        if result.returncode == 0:
            print(f"\n{result.stdout.strip()}")
        else:
            sys.exit(f"sbatch failed: {result.stderr.strip()}")


# =============================================================================
# Entry point
# =============================================================================

def main() -> None:
    parser = argparse.ArgumentParser(
        description="NVT protein MD workflow manager for AMBER.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument(
        "--config", default="config.yaml",
        help="Configuration file (default: config.yaml)",
    )

    sub = parser.add_subparsers(dest="command", required=True)

    p_setup = sub.add_parser("setup", help="Generate all input files and run scripts")
    p_setup.add_argument(
        "--mode", default="cluster", choices=["cluster", "local"],
        help="cluster (SLURM, default) or local (single GPU workstation)",
    )
    p_setup.add_argument(
        "--submit", action="store_true",
        help="Launch run_gpu (sbatch) or run_local (bash) after generating files",
    )

    p_submit = sub.add_parser(
        "submit", help="Submit existing scripts without regenerating files",
    )
    p_submit.add_argument(
        "--mode", default="cluster", choices=["cluster", "local"],
        help="Must match the mode used during setup (default: cluster)",
    )

    # Parse config first so execution_mode can serve as the default for --mode.
    args, _ = parser.parse_known_args()
    config_path = Path(args.config)
    if not config_path.exists():
        sys.exit(f"Config file not found: {config_path}")
    with open(config_path) as fh:
        cfg = yaml.safe_load(fh)

    cfg_mode = cfg.get("execution_mode", "cluster")
    p_setup.set_defaults(mode=cfg_mode)
    p_submit.set_defaults(mode=cfg_mode)

    args = parser.parse_args()

    if args.command == "setup":
        setup(cfg, mode=args.mode, submit=args.submit)
    elif args.command == "submit":
        _submit(cfg, mode=args.mode)


if __name__ == "__main__":
    main()
